-- Cable Bahamas app in Snowpark Container Services. Run as ACCOUNTADMIN:
--   snow sql -c PJOSE_AWS3_ADMIN --enable-templating NONE -f spcs/setup.sql
--
-- Roles
--   CABLE_BAHAMAS_APP     owns the service, image repository and compute pool.
--   CABLE_BAHAMAS_VIEWER  end users: sign in to the endpoint, query the agent, approve actions.
--
-- The service runs with caller's rights: each query executes as the signed-in user, limited to
-- the INTERSECTION of that user's privileges and the CALLER grants held by CABLE_BAHAMAS_APP.
-- Caller grants are scoped to ANALYTICS_V2 only, with writes limited to ACTION_LOG.
USE ROLE ACCOUNTADMIN;

-- 1. Owner role and infrastructure ------------------------------------------------------------
CREATE ROLE IF NOT EXISTS CABLE_BAHAMAS_APP COMMENT = 'Owns the Cable Bahamas SPCS web service';
GRANT ROLE CABLE_BAHAMAS_APP TO ROLE ACCOUNTADMIN;
CREATE SCHEMA IF NOT EXISTS CABLEBAHAMAS_DEMO.APP COMMENT = 'Cable Bahamas SPCS web app';
GRANT USAGE ON DATABASE CABLEBAHAMAS_DEMO TO ROLE CABLE_BAHAMAS_APP;
GRANT USAGE, CREATE SERVICE, CREATE IMAGE REPOSITORY ON SCHEMA CABLEBAHAMAS_DEMO.APP TO ROLE CABLE_BAHAMAS_APP;
GRANT CREATE COMPUTE POOL ON ACCOUNT TO ROLE CABLE_BAHAMAS_APP;
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE CABLE_BAHAMAS_APP;
GRANT USAGE ON WAREHOUSE DC_WAREHOUSE TO ROLE CABLE_BAHAMAS_APP;

USE ROLE CABLE_BAHAMAS_APP;
CREATE IMAGE REPOSITORY IF NOT EXISTS CABLEBAHAMAS_DEMO.APP.IMAGES;
CREATE COMPUTE POOL IF NOT EXISTS CABLE_BAHAMAS_POOL
  MIN_NODES = 1 MAX_NODES = 1 INSTANCE_FAMILY = CPU_X64_XS
  AUTO_SUSPEND_SECS = 3600 AUTO_RESUME = TRUE
  COMMENT = 'Cable Bahamas web app (XS, 1 node, suspends after 1h idle)';
USE ROLE ACCOUNTADMIN;

-- 2. Viewer role (end users) ------------------------------------------------------------------
CREATE ROLE IF NOT EXISTS CABLE_BAHAMAS_VIEWER COMMENT = 'Uses the Cable Bahamas app and agent; read-only except ACTION_LOG decisions';
GRANT ROLE CABLE_BAHAMAS_VIEWER TO USER PJOSE;
GRANT USAGE ON DATABASE CABLEBAHAMAS_DEMO TO ROLE CABLE_BAHAMAS_VIEWER;
GRANT USAGE ON SCHEMA CABLEBAHAMAS_DEMO.APP TO ROLE CABLE_BAHAMAS_VIEWER;
GRANT USAGE ON SCHEMA CABLEBAHAMAS_DEMO.ANALYTICS_V2 TO ROLE CABLE_BAHAMAS_VIEWER;
GRANT USAGE ON WAREHOUSE DC_WAREHOUSE TO ROLE CABLE_BAHAMAS_VIEWER;
GRANT SELECT ON ALL TABLES IN SCHEMA CABLEBAHAMAS_DEMO.ANALYTICS_V2 TO ROLE CABLE_BAHAMAS_VIEWER;
GRANT SELECT ON ALL SEMANTIC VIEWS IN SCHEMA CABLEBAHAMAS_DEMO.ANALYTICS_V2 TO ROLE CABLE_BAHAMAS_VIEWER;
GRANT INSERT, UPDATE ON TABLE CABLEBAHAMAS_DEMO.ANALYTICS_V2.ACTION_LOG TO ROLE CABLE_BAHAMAS_VIEWER;
GRANT USAGE ON PROCEDURE CABLEBAHAMAS_DEMO.ANALYTICS_V2.PROPOSE_ACTION(VARCHAR, VARCHAR, VARCHAR) TO ROLE CABLE_BAHAMAS_VIEWER;
GRANT USAGE ON AGENT CABLEBAHAMAS_DEMO.ANALYTICS_V2.CABLE_BAHAMAS_AGENT TO ROLE CABLE_BAHAMAS_VIEWER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE CABLE_BAHAMAS_VIEWER;

-- 3. Caller grants on the service owner (scoped to ANALYTICS_V2) ------------------------------
GRANT CALLER USAGE ON DATABASE CABLEBAHAMAS_DEMO TO ROLE CABLE_BAHAMAS_APP;
GRANT CALLER USAGE ON SCHEMA CABLEBAHAMAS_DEMO.ANALYTICS_V2 TO ROLE CABLE_BAHAMAS_APP;
GRANT CALLER USAGE ON WAREHOUSE DC_WAREHOUSE TO ROLE CABLE_BAHAMAS_APP;
GRANT INHERITED CALLER SELECT ON ALL TABLES IN SCHEMA CABLEBAHAMAS_DEMO.ANALYTICS_V2 TO ROLE CABLE_BAHAMAS_APP;
GRANT INHERITED CALLER SELECT ON ALL SEMANTIC VIEWS IN SCHEMA CABLEBAHAMAS_DEMO.ANALYTICS_V2 TO ROLE CABLE_BAHAMAS_APP;
GRANT CALLER INSERT, UPDATE ON TABLE CABLEBAHAMAS_DEMO.ANALYTICS_V2.ACTION_LOG TO ROLE CABLE_BAHAMAS_APP;
GRANT CALLER USAGE ON PROCEDURE CABLEBAHAMAS_DEMO.ANALYTICS_V2.PROPOSE_ACTION(VARCHAR, VARCHAR, VARCHAR) TO ROLE CABLE_BAHAMAS_APP;
GRANT CALLER USAGE ON AGENT CABLEBAHAMAS_DEMO.ANALYTICS_V2.CABLE_BAHAMAS_AGENT TO ROLE CABLE_BAHAMAS_APP;
SHOW CALLER GRANTS TO ROLE CABLE_BAHAMAS_APP;

