CREATE TABLE CABLEBAHAMAS_DEMO.ANALYTICS.B2B_PIPELINE AS
WITH generated AS (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS N FROM TABLE(GENERATOR(ROWCOUNT=>80)))
SELECT 'OPP-'||LPAD(N::VARCHAR,4,'0') AS OPPORTUNITY_ID,'Demo Business '||N AS ACCOUNT_NAME,
CASE MOD(N,4) WHEN 0 THEN 'Hospitality' WHEN 1 THEN 'Retail' WHEN 2 THEN 'Professional Services' ELSE 'Logistics' END AS INDUSTRY,
CASE MOD(N,4) WHEN 0 THEN 'New Providence' WHEN 1 THEN 'Grand Bahama' WHEN 2 THEN 'Abaco' ELSE 'Exuma' END AS ISLAND,
IFF(MOD(N,2)=0,'Business Dedicated Gigabit','Business Fibre 500') AS PRODUCT_NAME,
CASE MOD(N,5) WHEN 0 THEN 'Closed Won' WHEN 1 THEN 'Closed Lost' WHEN 2 THEN 'Proposal' WHEN 3 THEN 'Negotiation' ELSE 'Qualification' END AS STAGE,
CASE MOD(N,5) WHEN 0 THEN 1.0 WHEN 1 THEN 0.0 WHEN 2 THEN 0.5 WHEN 3 THEN 0.75 ELSE 0.2 END AS WIN_PROBABILITY,
(3000+MOD(N,12)*1200)::NUMBER(12,2) AS ANNUAL_CONTRACT_VALUE_BSD,
DATEADD('day',-MOD(N*3,120),'2026-05-31'::DATE)::DATE AS CREATED_DATE,
DATEADD('day',IFF(MOD(N,5) IN (0,1),-MOD(N*5,90),MOD(N*7,90)),'2026-05-31'::DATE)::DATE AS CLOSE_DATE,
'Demo Rep '||(1+MOD(N,4)) AS OWNER_NAME,
'2026-05-31'::DATE AS SNAPSHOT_DATE,
'Synthetic pipeline; open stages only for pipeline; won and lost only for win rate'::VARCHAR AS DATA_NOTE
FROM generated;
