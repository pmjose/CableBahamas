CREATE TABLE CABLEBAHAMAS_DEMO.ANALYTICS.NETWORK_DAILY AS
WITH sites AS (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS SITE_NUM FROM TABLE(GENERATOR(ROWCOUNT=>28))),
days AS (SELECT DATEADD('day',ROW_NUMBER() OVER (ORDER BY SEQ4())-1,'2026-05-01'::DATE)::DATE AS OBSERVED_DATE FROM TABLE(GENERATOR(ROWCOUNT=>31)))
SELECT 'SITE-'||LPAD(S.SITE_NUM::VARCHAR,3,'0') AS SITE_ID,D.OBSERVED_DATE,
 CASE MOD(S.SITE_NUM-1,7) WHEN 0 THEN 'New Providence' WHEN 1 THEN 'Grand Bahama' WHEN 2 THEN 'Abaco'
 WHEN 3 THEN 'Eleuthera' WHEN 4 THEN 'Exuma' WHEN 5 THEN 'Andros' ELSE 'Bimini' END AS ISLAND,
 IFF(MOD(S.SITE_NUM,2)=0,'FTTH','HFC') AS ACCESS_TECHNOLOGY,
 CASE MOD(S.SITE_NUM-1,7) WHEN 0 THEN 25.0443 WHEN 1 THEN 26.5333 WHEN 2 THEN 26.5412 WHEN 3 THEN 25.1962 WHEN 4 THEN 23.5000 WHEN 5 THEN 24.7064 ELSE 25.7270 END AS LATITUDE,
 CASE MOD(S.SITE_NUM-1,7) WHEN 0 THEN -77.3504 WHEN 1 THEN -78.7000 WHEN 2 THEN -77.0636 WHEN 3 THEN -76.2431 WHEN 4 THEN -75.7667 WHEN 5 THEN -77.7902 ELSE -79.2972 END AS LONGITUDE,
 400+S.SITE_NUM*20 AS HOMES_PASSED,
 120+S.SITE_NUM*7 AS CONNECTED_PREMISES,
 30+MOD(S.SITE_NUM*7+DAY(D.OBSERVED_DATE)*3,66) AS UTILIZATION_PCT,
 100-IFF(MOD(S.SITE_NUM+DAY(D.OBSERVED_DATE),13)=0,1.5,0.02) AS AVAILABILITY_PCT,
 IFF(MOD(S.SITE_NUM+DAY(D.OBSERVED_DATE),13)=0,21.6,0.288)::NUMBER(12,3) AS OUTAGE_MINUTES,
 40+MOD(S.SITE_NUM*19,300) AS AVERAGE_DOWNLOAD_MBPS,
 IFF(MOD(S.SITE_NUM+DAY(D.OBSERVED_DATE),13)=0,'Degraded','Healthy') AS STATUS,
 'Synthetic site-day; count distinct sites and use one date for premises snapshots'::VARCHAR AS DATA_NOTE
FROM sites S CROSS JOIN days D;
