CREATE TABLE CABLEBAHAMAS_DEMO.ANALYTICS.CUSTOMERS AS
WITH generated AS (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS N FROM TABLE(GENERATOR(ROWCOUNT=>1200))),
assigned AS (
 SELECT N, 'CBL-' || LPAD(N::VARCHAR,6,'0') AS CUSTOMER_ID,
 CASE WHEN MOD(N,10)=0 THEN 'P08' WHEN MOD(N,10)=1 THEN 'P07'
 WHEN MOD(N,10) IN (2,3) THEN 'P06' WHEN MOD(N,10)=4 THEN 'P01'
 WHEN MOD(N,10) IN (5,6) THEN 'P02' WHEN MOD(N,10)=7 THEN 'P03'
 WHEN MOD(N,10)=8 THEN 'P04' ELSE 'P05' END AS PRODUCT_ID,
 CASE WHEN MOD(N,20)<10 THEN 'New Providence' WHEN MOD(N,20)<14 THEN 'Grand Bahama'
 WHEN MOD(N,20)<16 THEN 'Abaco' WHEN MOD(N,20)=16 THEN 'Eleuthera'
 WHEN MOD(N,20)=17 THEN 'Exuma' WHEN MOD(N,20)=18 THEN 'Andros' ELSE 'Bimini' END AS ISLAND
 FROM generated)
SELECT A.CUSTOMER_ID, 'Demo Account ' || LPAD(A.N::VARCHAR,4,'0') AS CUSTOMER_NAME,
 A.PRODUCT_ID,P.PRODUCT_NAME,P.SERVICE_FAMILY,P.CUSTOMER_SEGMENT,A.ISLAND,
 CASE A.ISLAND WHEN 'New Providence' THEN 'Nassau' WHEN 'Grand Bahama' THEN 'Freeport'
 WHEN 'Abaco' THEN 'Marsh Harbour' WHEN 'Eleuthera' THEN 'Governors Harbour'
 WHEN 'Exuma' THEN 'George Town' WHEN 'Andros' THEN 'Andros Town' ELSE 'Alice Town' END AS TOWN,
 DATEADD('month',-1-MOD(A.N,84),'2026-05-31'::DATE)::DATE AS JOIN_DATE,
 DATEDIFF('month',DATEADD('month',-1-MOD(A.N,84),'2026-05-31'::DATE),'2026-05-31'::DATE) AS TENURE_MONTHS,
 P.MONTHLY_PRICE_BSD AS CURRENT_MRR_BSD,
 MOD(A.N*37,100)/100.0 AS CHURN_SCORE,
 CASE WHEN MOD(A.N*37,100)>=75 THEN 'High' WHEN MOD(A.N*37,100)>=40 THEN 'Medium' ELSE 'Low' END AS CHURN_RISK,
 CASE WHEN MOD(A.N,4)=0 THEN 'Platinum' WHEN MOD(A.N,4)=1 THEN 'Gold' WHEN MOD(A.N,4)=2 THEN 'Silver' ELSE 'Bronze' END AS TIER,
 MOD(A.N*13,11) AS NPS_SCORE,
 MOD(A.N,5)<>0 AS MARKETING_CONSENT,
 ROUND((P.MONTHLY_PRICE_BSD-P.MONTHLY_COST_BSD)*24*(1-MOD(A.N*37,100)/200.0),2) AS EXPECTED_24M_CLV_BSD,
 '2026-05-31'::DATE AS SNAPSHOT_DATE,
 'Synthetic; one primary fixed-service contract per account'::VARCHAR AS DATA_NOTE
FROM assigned A JOIN CABLEBAHAMAS_DEMO.ANALYTICS.PRODUCTS P ON A.PRODUCT_ID=P.PRODUCT_ID;
