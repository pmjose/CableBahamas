-- Agent tool: logs a proposed action for human approval. Never executes it.
CREATE OR REPLACE PROCEDURE CABLEBAHAMAS_DEMO.ANALYTICS_V2.PROPOSE_ACTION(TITLE VARCHAR, DETAIL VARCHAR, CATEGORY VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Logs an agent-proposed action for human approval. Never executes the action.'
EXECUTE AS OWNER
AS
$$
DECLARE
  new_id VARCHAR DEFAULT UUID_STRING();
BEGIN
  INSERT INTO CABLEBAHAMAS_DEMO.ANALYTICS_V2.ACTION_LOG (ACTION_ID, TITLE, DETAIL, CATEGORY, STATUS, PROPOSED_BY, PROPOSED_AT)
    VALUES (:new_id, LEFT(:TITLE, 200), LEFT(:DETAIL, 1000), LOWER(LEFT(:CATEGORY, 30)), 'PENDING_APPROVAL', 'CABLE_BAHAMAS_AGENT', CURRENT_TIMESTAMP());
  RETURN OBJECT_CONSTRUCT('action_id', :new_id, 'title', :TITLE, 'detail', :DETAIL, 'status', 'PENDING_APPROVAL')::VARCHAR;
END;
$$;
