CREATE TABLE CABLEBAHAMAS_DEMO.ANALYTICS.MONTHLY_FINANCE AS
WITH months AS (SELECT DATEADD('month',ROW_NUMBER() OVER (ORDER BY SEQ4())-1,'2025-06-01'::DATE)::DATE AS MONTH_START FROM TABLE(GENERATOR(ROWCOUNT=>12))),
base AS (
 SELECT M.MONTH_START,C.PRODUCT_ID,C.PRODUCT_NAME,C.SERVICE_FAMILY,C.CUSTOMER_SEGMENT,C.ISLAND,
 COUNT(*) AS ACTIVE_ACCOUNTS,
 SUM(C.CURRENT_MRR_BSD) AS REVENUE_BSD,
 SUM(P.MONTHLY_COST_BSD) AS COST_OF_SERVICE_BSD,
 ROUND(SUM(C.CURRENT_MRR_BSD)*0.18,2) AS OPERATING_EXPENSE_BSD
 FROM months M JOIN CABLEBAHAMAS_DEMO.ANALYTICS.CUSTOMERS C ON C.JOIN_DATE<=LAST_DAY(M.MONTH_START)
 JOIN CABLEBAHAMAS_DEMO.ANALYTICS.PRODUCTS P ON C.PRODUCT_ID=P.PRODUCT_ID
 GROUP BY ALL)
SELECT *, REVENUE_BSD-COST_OF_SERVICE_BSD AS GROSS_PROFIT_BSD,
 REVENUE_BSD-COST_OF_SERVICE_BSD-OPERATING_EXPENSE_BSD AS EBITDA_BSD,
 ROUND(REVENUE_BSD*1.04,2) AS BUDGET_REVENUE_BSD,
 ROUND(REVENUE_BSD*0.12,2) AS CAPEX_BSD,
 ROUND(REVENUE_BSD*0.06,2) AS DEPRECIATION_BSD,
 'Synthetic accrued revenue; active accounts are snapshots, never sum across months'::VARCHAR AS DATA_NOTE
FROM base;
