UPDATE CABLEBAHAMAS_DEMO.ANALYTICS.SUPPORT_CASES S
SET OPENED_DATE=GREATEST(S.OPENED_DATE,C.JOIN_DATE)
FROM CABLEBAHAMAS_DEMO.ANALYTICS.CUSTOMERS C
WHERE S.CUSTOMER_ID=C.CUSTOMER_ID AND S.OPENED_DATE<C.JOIN_DATE;

UPDATE CABLEBAHAMAS_DEMO.ANALYTICS.B2B_PIPELINE
SET CREATED_DATE=DATEADD('day',-30,CLOSE_DATE)
WHERE CREATED_DATE>CLOSE_DATE;
