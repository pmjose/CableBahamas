CREATE TABLE CABLEBAHAMAS_DEMO.ANALYTICS.SUPPORT_CASES AS
WITH generated AS (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS N FROM TABLE(GENERATOR(ROWCOUNT=>480)))
SELECT 'CASE-'||LPAD(G.N::VARCHAR,5,'0') AS CASE_ID,C.CUSTOMER_ID,C.ISLAND,C.TOWN,C.SERVICE_FAMILY,C.CUSTOMER_SEGMENT,
 DATEADD('day',-MOD(G.N*7,365),'2026-05-31'::DATE)::DATE AS OPENED_DATE,
 CASE WHEN MOD(G.N,5)=0 THEN 'Open' ELSE 'Resolved' END AS STATUS,
 CASE MOD(G.N,4) WHEN 0 THEN 'Outage' WHEN 1 THEN 'Slow speed' WHEN 2 THEN 'Billing' ELSE 'Installation' END AS CATEGORY,
 CASE WHEN MOD(G.N,8)=0 THEN 'P1' WHEN MOD(G.N,3)=0 THEN 'P2' ELSE 'P3' END AS PRIORITY,
 CASE MOD(G.N,3) WHEN 0 THEN 'Phone' WHEN 1 THEN 'Web' ELSE 'Retail' END AS CHANNEL,
 IFF(MOD(G.N,5)=0,NULL,2+MOD(G.N*11,70))::NUMBER AS RESOLUTION_HOURS,
 24::NUMBER AS SLA_TARGET_HOURS,
 IFF(MOD(G.N,5)=0,NULL,(2+MOD(G.N*11,70))<=24) AS SLA_MET,
 IFF(MOD(G.N,5)=0,NULL,1+MOD(G.N,5))::NUMBER AS CSAT_SCORE,
 'Synthetic; open cases have null resolution time and CSAT'::VARCHAR AS DATA_NOTE
FROM generated G JOIN CABLEBAHAMAS_DEMO.ANALYTICS.CUSTOMERS C
 ON C.CUSTOMER_ID='CBL-'||LPAD((1+MOD(G.N*17,1200))::VARCHAR,6,'0');
