CREATE TABLE CABLEBAHAMAS_DEMO.ANALYTICS.INVOICES AS
WITH months AS (SELECT DATEADD('month',ROW_NUMBER() OVER (ORDER BY SEQ4())-1,'2025-06-01'::DATE)::DATE AS MONTH_START FROM TABLE(GENERATOR(ROWCOUNT=>12))),
base AS (
SELECT C.CUSTOMER_ID||'-'||TO_CHAR(M.MONTH_START,'YYYYMM') AS INVOICE_ID,C.CUSTOMER_ID,C.ISLAND,C.SERVICE_FAMILY,C.CUSTOMER_SEGMENT,
M.MONTH_START AS INVOICE_DATE,DATEADD('day',14,M.MONTH_START)::DATE AS DUE_DATE,C.CURRENT_MRR_BSD AS AMOUNT_BSD,
IFF(MOD(TRY_TO_NUMBER(SPLIT_PART(C.CUSTOMER_ID,'-',2))+MONTH(M.MONTH_START),17)=0,0,C.CURRENT_MRR_BSD) AS PAID_BSD
FROM months M JOIN CABLEBAHAMAS_DEMO.ANALYTICS.CUSTOMERS C ON C.JOIN_DATE<=LAST_DAY(M.MONTH_START))
SELECT *,AMOUNT_BSD-PAID_BSD AS OUTSTANDING_BSD,
IFF(AMOUNT_BSD=PAID_BSD,0,GREATEST(DATEDIFF('day',DUE_DATE,'2026-05-31'::DATE),0)) AS DAYS_OVERDUE,
IFF(AMOUNT_BSD=PAID_BSD,'Paid','Overdue') AS STATUS,
'2026-05-31'::DATE AS AS_OF_DATE,
'Synthetic invoice; billed amount reconciles to accrued revenue at monthly grain'::VARCHAR AS DATA_NOTE
FROM base;
