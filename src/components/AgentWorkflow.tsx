import { useEffect, useRef, useState } from 'react'
import {
  Zap, ListChecks, Wrench, UserCheck, CheckCircle2, ScrollText, Play, RotateCcw, XCircle, Loader2, Bot, ShieldCheck,
} from 'lucide-react'
import tt from '../i18n/tt'
import type { AgentFlow } from '../pages/portal/_agent_flows'

type Phase = 'idle' | 'planning' | 'tools' | 'approval' | 'acting' | 'done' | 'rejected'

const STEP_MS = 650

/**
 * Agentic workflow player: trigger → plan → tool calls → human approval →
 * actions → audit trail. Scripted simulation; no real system is called.
 */
export default function AgentWorkflow({ flow, compact = false }: { flow: AgentFlow; compact?: boolean }) {
  const [phase, setPhase] = useState<Phase>('idle')
  const [planShown, setPlanShown] = useState(0)
  const [toolsShown, setToolsShown] = useState(0)
  const [actionsShown, setActionsShown] = useState(0)
  const [audit, setAudit] = useState<string[]>([])
  const timer = useRef<ReturnType<typeof setTimeout>>()

  useEffect(() => () => clearTimeout(timer.current), [])

  const log = (entry: string) => setAudit(a => [...a, entry])

  // Advance whichever phase is active one item at a time.
  useEffect(() => {
    if (phase === 'planning') {
      if (planShown < flow.plan.length) timer.current = setTimeout(() => setPlanShown(n => n + 1), STEP_MS)
      else { log(tt('Plan generated by') + ' ' + tt(flow.orchestrator)); setPhase('tools') }
    } else if (phase === 'tools') {
      if (toolsShown < flow.tools.length) timer.current = setTimeout(() => setToolsShown(n => n + 1), STEP_MS)
      else { log(`${flow.tools.length} ${tt('tool calls completed · read-only')}`); setPhase('approval') }
    } else if (phase === 'acting') {
      if (actionsShown < flow.actions.length) {
        timer.current = setTimeout(() => {
          log(`${tt('Executed')}: ${tt(flow.actions[actionsShown].label)}`)
          setActionsShown(n => n + 1)
        }, STEP_MS)
      } else { log(tt('Workflow closed · outcome written to audit table')); setPhase('done') }
    }
  }, [phase, planShown, toolsShown, actionsShown, flow])

  const start = () => {
    clearTimeout(timer.current)
    setPlanShown(0); setToolsShown(0); setActionsShown(0)
    setAudit([`${tt('Triggered')}: ${tt(flow.trigger.event)}`])
    setPhase('planning')
  }
  const approve = () => { log(`${tt('Approved by')} ${tt(flow.approval.approver)}`); setPhase('acting') }
  const reject = () => { log(`${tt('Rejected by')} ${tt(flow.approval.approver)} · ${tt('no actions taken')}`); setPhase('rejected') }

  const running = phase === 'planning' || phase === 'tools' || phase === 'acting'
  const reached = (p: Phase) => {
    const order: Phase[] = ['idle', 'planning', 'tools', 'approval', 'acting', 'done']
    const cur = phase === 'rejected' ? 'approval' : phase
    return order.indexOf(cur) >= order.indexOf(p)
  }

  return (
    <div className="rounded-2xl border border-vfes-red/20 bg-gradient-to-br from-vfes-red/5 to-white p-5">
      <div className="flex items-start justify-between gap-3 flex-wrap mb-4">
        <div>
          <div className="flex items-center gap-2 text-[10px] font-bold uppercase tracking-widest text-vfes-dark/70">
            <Bot className="w-3 h-3" /> {tt('Agentic workflow')} · {tt(flow.orchestrator)}
          </div>
          <h3 className="text-lg font-extrabold text-vfes-dark mt-1">{tt(flow.title)}</h3>
          {!compact && <p className="text-xs text-vfes-dark/60 mt-0.5 max-w-3xl">{tt(flow.summary)}</p>}
        </div>
        {phase === 'idle' && (
          <button onClick={start} className="inline-flex items-center gap-1.5 bg-vfes-red text-vfes-dark text-sm font-bold px-4 py-2 rounded-full hover:opacity-90">
            <Play className="w-4 h-4" /> {tt('Run workflow')}
          </button>
        )}
        {(phase === 'done' || phase === 'rejected') && (
          <button onClick={start} className="inline-flex items-center gap-1.5 bg-black/5 text-vfes-dark text-sm font-semibold px-4 py-2 rounded-full hover:bg-black/10">
            <RotateCcw className="w-4 h-4" /> {tt('Replay')}
          </button>
        )}
        {running && (
          <span className="inline-flex items-center gap-1.5 text-xs font-semibold text-vfes-dark/70">
            <Loader2 className="w-4 h-4 animate-spin" /> {tt('Agent working…')}
          </span>
        )}
      </div>

      <div className="flex flex-wrap gap-2 mb-4">
        {flow.agents.map(a => (
          <span key={a} className="text-[10px] font-semibold px-2 py-1 rounded-full bg-white border border-black/10 text-vfes-dark/70">{tt(a)}</span>
        ))}
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-5 gap-3">
        <Stage icon={Zap} title="Trigger" active>
          <div className="text-xs font-semibold text-vfes-dark">{tt(flow.trigger.event)}</div>
          <div className="text-[11px] text-vfes-dark/55 mt-1">{tt(flow.trigger.source)}</div>
        </Stage>

        <Stage icon={ListChecks} title="Plan" active={reached('planning')}>
          <ol className="space-y-1">
            {flow.plan.slice(0, planShown).map((p, i) => (
              <li key={i} className="text-[11px] text-vfes-dark/80 flex gap-1.5"><span className="font-mono text-vfes-dark/40">{i + 1}.</span>{tt(p)}</li>
            ))}
          </ol>
        </Stage>

        <Stage icon={Wrench} title="Tool calls" active={reached('tools')}>
          <ul className="space-y-1.5">
            {flow.tools.slice(0, toolsShown).map((t, i) => (
              <li key={i} className="text-[11px]">
                <div className="font-mono text-[10px] text-vfes-dark/50">{t.tool}</div>
                <div className="text-vfes-dark/80">{tt(t.result)}</div>
              </li>
            ))}
          </ul>
        </Stage>

        <Stage icon={UserCheck} title="Human approval" active={reached('approval')}>
          {reached('approval') && (
            <div>
              <div className="text-xs font-semibold text-vfes-dark">{tt(flow.approval.ask)}</div>
              <div className="text-[11px] text-vfes-dark/55 mt-1">{tt('Approver')}: {tt(flow.approval.approver)}</div>
              <div className="text-[11px] text-amber-700 mt-1">{tt('Guardrail')}: {tt(flow.approval.guardrail)}</div>
              {phase === 'approval' && (
                <div className="flex gap-2 mt-2">
                  <button onClick={approve} className="text-xs font-bold px-3 py-1.5 rounded-full bg-emerald-600 text-white hover:bg-emerald-700">{tt('Approve')}</button>
                  <button onClick={reject} className="text-xs font-semibold px-3 py-1.5 rounded-full bg-black/5 hover:bg-black/10">{tt('Reject')}</button>
                </div>
              )}
              {phase === 'rejected' && <div className="mt-2 inline-flex items-center gap-1 text-xs font-semibold text-red-600"><XCircle className="w-3.5 h-3.5" /> {tt('Rejected · no actions taken')}</div>}
            </div>
          )}
        </Stage>

        <Stage icon={CheckCircle2} title="Actions" active={reached('acting')}>
          <ul className="space-y-1.5">
            {flow.actions.slice(0, actionsShown).map((a, i) => (
              <li key={i} className="text-[11px] flex gap-1.5">
                <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600 shrink-0 mt-0.5" />
                <span><span className="font-semibold text-vfes-dark">{tt(a.label)}</span><span className="text-vfes-dark/55"> · {tt(a.system)}</span></span>
              </li>
            ))}
          </ul>
        </Stage>
      </div>

      {phase === 'done' && (
        <div className="mt-4 flex flex-wrap gap-2">
          {flow.outcome.map(o => (
            <div key={o.label} className="rounded-lg bg-white border border-emerald-200 px-3 py-2">
              <div className="text-[10px] uppercase tracking-widest text-vfes-dark/50 font-bold">{tt(o.label)}</div>
              <div className="text-sm font-extrabold text-emerald-700">{tt(o.value)}</div>
            </div>
          ))}
        </div>
      )}

      {audit.length > 0 && !compact && (
        <div className="mt-4 rounded-lg bg-vfes-dark/[0.03] border border-black/5 p-3">
          <div className="flex items-center gap-1.5 text-[10px] font-bold uppercase tracking-widest text-vfes-dark/50 mb-1.5"><ScrollText className="w-3 h-3" /> {tt('Audit trail')}</div>
          <ol className="space-y-0.5 font-mono text-[10px] text-vfes-dark/65">
            {audit.map((e, i) => <li key={i}>{String(i + 1).padStart(2, '0')} · {e}</li>)}
          </ol>
        </div>
      )}

      <div className="mt-3 flex items-center gap-1.5 text-[10px] text-vfes-dark/45">
        <ShieldCheck className="w-3 h-3 shrink-0" />
        {tt('Simulated workflow on synthetic data · no real system is called · customer-facing and financial actions require human approval.')}
      </div>
    </div>
  )
}

function Stage({ icon: Icon, title, active, children }: { icon: any; title: string; active: boolean; children?: React.ReactNode }) {
  return (
    <div className={`rounded-xl border p-3 min-h-[120px] transition ${active ? 'bg-white border-black/10' : 'bg-white/40 border-dashed border-black/10 opacity-60'}`}>
      <div className="flex items-center gap-1.5 text-[10px] font-bold uppercase tracking-widest text-vfes-dark/60 mb-2">
        <Icon className="w-3.5 h-3.5" /> {tt(title)}
      </div>
      {active && children}
    </div>
  )
}
